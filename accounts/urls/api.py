from django.urls import path
from ..views.api import (
    LoginView,
    RegisterView,
    RequestPasswordReset,
    ResetPassword,
    PasswordResetCheckToken,
    UpdateUserCompany,
    UserBankDetailsApiView,
    UserBeneficiariesApiView,
    UserProfileView,
    verify_email,
    verify_email_success,
    verify_email_failure,
    VerifyAndSetPassword,
    UserDetailView,
    InviteUser,
    UserListView,
    GetOTP,
    VerifyOTP,
    CheckPhoneNumberUniquenessView,
    SyncUserData,
)

app_name = 'accounts-api'

urlpatterns = [
    path('login', LoginView.as_view(), name='login'),
    path('register', RegisterView.as_view(), name='register'),
    path('verify-email/<str:uidb64>/<str:token>', verify_email, name='verify-email'),
    path('verify-email-success', verify_email_success, name='verify-email-success'),
    path('verify-email-failure', verify_email_failure, name='verify-email-failure'),
    path('verify-access-token', VerifyAndSetPassword.as_view(), name='verify-access-token'),
    path('reset-password-request', RequestPasswordReset.as_view(), name='reset-password-request'),
    path('reset-password-token', PasswordResetCheckToken.as_view(), name='reset-password-token'),
    path('reset-password', ResetPassword.as_view(), name='reset-password'),
    path('users/<str:pk>', UserDetailView.as_view(), name='user-detail'),
    path('invite-user', InviteUser.as_view(), name='invite-user'),
    path('users', UserListView.as_view(), name='user-list'),
    path('profile', UserProfileView.as_view(), name='profile'),
    path('profile/companies', UpdateUserCompany.as_view(), name='profile-companies'),
    path('bank-details', UserBankDetailsApiView.as_view(), name='bank-details'),
    path('bank-details/<str:pk>', UserBankDetailsApiView.as_view(), name='bank-details-detail'),
    path('beneficiaries-bank-details', UserBeneficiariesApiView.as_view(), name='beneficiaries-bank-details'),
    path('beneficiaries-bank-details/<str:pk>', UserBeneficiariesApiView.as_view(),
         name='beneficiaries-bank-details-detail'),
    path('generate-otp/', GetOTP.as_view(), name='generate-otp'),
    path('verify-otp/', VerifyOTP.as_view(), name='verify-otp'),
    path('check-unique-phone-number/', CheckPhoneNumberUniquenessView.as_view(), name='check-unique-phone-number'),
    path('sync', SyncUserData.as_view(), name='sync'),
]
